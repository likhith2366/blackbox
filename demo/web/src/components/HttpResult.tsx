import { useState } from 'react'
import { fmtMs, isOk, type HttpOutcome } from '../lib/http'
import { Pill, type Tone } from './ui'

function tone(o: HttpOutcome): Tone {
  if (o.kind !== 'response') return 'bad'
  if (isOk(o)) return 'ok'
  return o.status !== undefined && o.status >= 500 ? 'bad' : 'warn'
}

function statusLabel(o: HttpOutcome): string {
  switch (o.kind) {
    case 'response':
      return `HTTP ${o.status}${o.statusText ? ' ' + o.statusText : ''}`
    case 'proxy-error':
      return 'upstream unreachable (dev proxy)'
    case 'client-timeout':
      return 'client timeout'
    case 'network-error':
      return 'network error'
  }
}

export function StatusBadge({ o }: { o: HttpOutcome }) {
  return <Pill tone={tone(o)}>{statusLabel(o)}</Pill>
}

/** Raw body exactly as returned (pretty-printed only if it parsed as JSON). */
export function RawBody({ o }: { o: HttpOutcome }) {
  if (o.kind === 'client-timeout' || o.kind === 'network-error')
    return <pre className="raw">{o.errorMessage}</pre>
  if (!o.bodyText) return <pre className="raw muted">(empty body)</pre>
  const text = o.bodyJson !== undefined ? JSON.stringify(o.bodyJson, null, 2) : o.bodyText
  return <pre className="raw">{text}</pre>
}

/** Compact one-exchange view: status, duration, method+url and the raw body. */
export function HttpResult({ o, defaultOpen = true }: { o: HttpOutcome; defaultOpen?: boolean }) {
  const [open, setOpen] = useState(defaultOpen)
  return (
    <div className="http-result">
      <div className="http-line">
        <StatusBadge o={o} />
        <span className="mono">{fmtMs(o.durationMs)}</span>
        <span className="mono muted ellipsis">
          {o.method} {o.url}
        </span>
        <button className="link" onClick={() => setOpen(!open)} aria-expanded={open}>
          {open ? 'hide body' : 'show body'}
        </button>
      </div>
      {o.kind === 'proxy-error' && (
        <p className="hint">This 502 was generated by the Vite dev proxy, not by the service.</p>
      )}
      {open && <RawBody o={o} />}
    </div>
  )
}
